'  }, []);\n'
'\n'
'  const handleLogin = (userData, userToken) => {\n'
'    setUser(userData);\n'
'    setToken(userToken);\n'
'  };\n'
'\n'
'  const handleLogout = () => {\n'
'    localStorage.removeItem(' + chr(39) + 'bb_token' + chr(39) + ');\n'
'    localStorage.removeItem(' + chr(39) + 'bb_user' + chr(39) + ');\n'
